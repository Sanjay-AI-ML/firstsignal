import { createClerkClient } from "@clerk/backend";
import { spawnSync } from "node:child_process";
import assert from "node:assert/strict";
process.loadEnvFile(".env.local");
if (!process.env.CLERK_SECRET_KEY?.startsWith("sk_test_")) throw new Error("Development Clerk keys required; production accounts must not be used for QA.");
const clerk = createClerkClient({ secretKey: process.env.CLERK_SECRET_KEY, publishableKey: process.env.NEXT_PUBLIC_CLERK_PUBLISHABLE_KEY });
const users = [];
const tokens = {};
try {
  for (const role of ["alice", "bob", "other"]) {
    const user = await clerk.users.createUser({ emailAddress: [`firstsignal-${role}-${crypto.randomUUID().slice(0, 12)}+clerk_test@example.com`], firstName: "QA", lastName: role, skipPasswordRequirement: true });
    users.push(user.id);
    const session = await clerk.sessions.createSession({ userId: user.id });
    tokens[role] = (await clerk.sessions.getToken(session.id)).jwt;
    if (role === "alice") {
      const origin = process.env.TEST_ORIGIN || "http://127.0.0.1:8787";
      if (!["127.0.0.1", "localhost"].includes(new URL(origin).hostname)) throw new Error("QA is local only.");
      const issuedAt = JSON.parse(Buffer.from(tokens[role].split(".")[1], "base64url")).iat;
      // Development cookie authentication also expects a browser marker. The
      // session itself is still the actual signed token generated by Clerk.
      const cookie = `__session=${tokens[role]}; __client_uat=${issuedAt}; __clerk_db_jwt=local-qa-browser`;
      const signedIn = await fetch(`${origin}/signin`, { headers: { Cookie: cookie } });
      assert.equal(signedIn.status, 200);
      assert.ok((await signedIn.text()).includes("Welcome back."), "Server must recognize the verified session cookie");
      const malformed = await fetch(`${origin}/api/workspace`, { method: "POST", headers: { Authorization: "Bearer invalid-token", Origin: origin, "Content-Type": "application/json" }, body: "{}" });
      assert.equal(malformed.status, 401);
      console.log("Session-cookie recognition and malformed-token rejection passed.");
    }
  }
  const result = spawnSync(process.execPath, ["scripts/verify-workflows.mjs"], { stdio: "inherit", env: { ...process.env, CLERK_QA_TOKENS: JSON.stringify(tokens) } });
  if (result.status !== 0) process.exitCode = result.status || 1;
} finally {
  for (const id of users) await clerk.users.deleteUser(id);
  console.log("Temporary Clerk QA accounts removed; no test data was written to the published database.");
}
